#!/bin/sh
# The plan's big-endian (or any cross) native check: a test program is
# compiled to C by this tree's native compiler, cross-compiled for the
# target, and linked statically into an executable carrying the
# target's world and the emulator, with the module registered at build
# time -- LOAD-EMBEDDED-PROGRAM skips the .oa header lines, so no
# dlopen is needed and a fully static binary works under qemu-user.
# The run must print byte for byte what the host's run prints.
#
#   sh tests/qemu-native.sh CROSSTREE CROSSCC QEMU [PROG...]
#
# CROSSTREE: a build tree configured --host for the target, with its
# emulator and world built (the emulator may be a qemu wrapper; only
# liboakrt.a, config.h and oakworld.bin are used here).  CROSSCC: a C
# compiler for the target ("zig cc -target s390x-linux-musl -std=gnu23
# -D_GNU_SOURCE" works, installed user-side with pip install ziglang).
# QEMU: the qemu-user binary, e.g. qemu-s390x.  PROG...: the test
# programs, loaded in order (default arith); several make a several-
# module executable, e.g. native-me native-check.

set -e
host=$(cd "$(dirname "$0")/.." && pwd)
testdir=$(cd "$(dirname "$0")" && pwd)
cross=${1?usage: qemu-native.sh CROSSTREE CROSSCC QEMU [PROG...]}
crosscc=${2?CROSSCC missing}
qemu=${3?QEMU missing}
shift 3
progs=${*-arith}
name=$(echo "$progs" | tr ' ' '+')

OAK="$host/src/emulator/oaklisp --batch --world $host/src/world/oakworld.bin"
test -f "$cross/src/emulator/liboakrt.a" || { echo "no cross liboakrt.a"; exit 1; }
test -f "$cross/src/world/oakworld.bin" || { echo "no cross world"; exit 1; }

# The target's bytecode architecture, read from its world's own header
# line: the host compiles the programs for it (--target), stubs
# included.
target=$(head -c 120 "$cross/src/world/oakworld.bin" \
  | sed -n 's/.*word-size=\([0-9]*\) instructions-per-ref=\([0-9]*\).*/bc\2-\1/p')
test -n "$target" || { echo "cannot read the target architecture"; exit 1; }
echo "qemu-native: target architecture $target"

work=$(mktemp -d "${TMPDIR:-/tmp}/oak-qemu.XXXXXX")
trap 'rm -rf "$work"' 0

prefixes=
objs=
loads=
for prog in $progs; do
  cp "$testdir/$prog.oak" "$work/"
  echo "qemu-native: compiling $prog.oak to C on the host"
  # OAK_QEMU_IR=1 compiles with the C-locals lowering on.
  irbind=
  test "${OAK_QEMU_IR-}" = 1 && irbind="(#*native-ir? #t) "
  (cd "$work" && $OAK -- --target "$target" --outdir . \
    --eval "(bind ((#*compiler-noisiness 0) (#*native-strict? #t) (#*native-emit-only? #t) $irbind) (native-compile-file system-locale \"$prog\"))" \
    --exit > compile.log 2>&1) \
    || { cat "$work/compile.log"; exit 1; }
  prefixes="$prefixes $(sed -n 's/^#define ON_PREFIX[ 	]*//p' "$work/$prog.c")"
  echo "qemu-native: cross-compiling $prog.c"
  $crosscc -DHAVE_CONFIG_H -DON_STATIC \
    -I"$cross/src/emulator" -I"$cross" -O2 \
    -c -o "$work/$prog.o" "$work/$prog.c"
  objs="$objs $work/$prog.o"
  loads="$loads --load $testdir/$prog"
  cat "$work/$prog.oa" >> "$work/program.oa"
done

hex() { od -An -v -tx1 "$1" | tr -s ' ' '\n' | sed '/^$/d; s/^/0x/; s/$/,/'; }
{
  echo '/* Generated by qemu-native.sh. */'
  echo '#include "oak-embed.h"'
  echo 'static const unsigned char the_world[] = {'
  hex "$cross/src/world/oakworld.bin"
  echo '};'
  echo 'static const unsigned char the_program[] = {'
  hex "$work/program.oa"
  echo '};'
  for p in $prefixes; do
    echo "extern const oak_native_module ${p}_module;"
  done
  echo 'static const oak_native_module *const mods[] = {'
  for p in $prefixes; do
    echo "  &${p}_module,"
  done
  echo '  0};'
  echo 'static const char *const args[] = {'
  echo '  "--batch", "--", "--load-embedded", "--exit"};'
  echo 'int main(int argc, char **argv) {'
  echo '  static oak_embedding e;'
  echo '  e.world = the_world; e.world_size = sizeof the_world;'
  echo '  e.program = (const char *)the_program;'
  echo '  e.program_size = sizeof the_program;'
  echo '  e.modules = mods;'
  echo '  e.module_count = sizeof mods / sizeof mods[0] - 1;'
  echo '  return oak_main_embedded(argc, argv, &e, args,'
  echo '			   (int)(sizeof args / sizeof args[0]));'
  echo '}'
} > "$work/main.c"
$crosscc -DHAVE_CONFIG_H -DON_STATIC \
  -I"$cross/src/emulator" -I"$cross" -O2 \
  -c -o "$work/main.o" "$work/main.c"

echo "qemu-native: linking"
$crosscc -static -o "$work/prog-x" "$work/main.o" $objs \
  "$cross/src/emulator/liboakrt.a" -lm

echo "qemu-native: the host's run"
$OAK -- $loads --exit 2>&1 \
  | grep -E '^(PASS|FAIL)' > "$work/want"
grep -q '^FAIL' "$work/want" && { echo "the host itself fails $name"; exit 1; }

echo "qemu-native: the target's run, under $qemu"
"$qemu" "$work/prog-x" 2>&1 | grep -E '^(PASS|FAIL)' > "$work/got"
cmp "$work/want" "$work/got" \
  || { diff "$work/want" "$work/got" | head; echo "qemu-native: output differs"; exit 1; }
echo "qemu-native: $name, $(grep -c '^PASS' "$work/got") checks, identical on the target"
